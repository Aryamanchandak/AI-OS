"""Pipeline-owned SQLite content store — the seven content tables (PLAN Phase 5).

Implements exactly the seven tables of `METADATA_SCHEMA_v1.0` §3:

    source · acquisition · highlight · comment · claim · transformation · tag

These are the **content** model (what was ingested and what the model claimed).
They are deliberately separate from the operational **ledger** tables in
`ingestion.store` (capture/review/dispatch/quarantine state) — different family,
different lifecycle. This store never reuses `ledger.db`; its path is explicit
and configurable (P0: tests pass a temp file; the permanent location is a
deferred data-layout decision).

Rebuildable projection: like Chroma, these rows are regenerated by the nightly
rebuild (T40) from immutable bronze. Never treat them as the source of truth.

Fail-fast + retry safety (PLAN Phase 4 / decision 3):
- `project_envelope` writes one source-unit in **one transaction**. A failure
  rolls the whole thing back — no half-written content is ever visible.
- Every row id is deterministic (`ingestion.ids`), and inserts are
  `INSERT OR IGNORE`, so redoing the same approved envelope produces no
  duplicates. A retry re-runs the same projection and lands on the same rows.
- Replacement (supersede) deletes the predecessor highlight's rows first, then
  projects the new envelope — delete-and-redo, no keep-old/verify machinery.

Fail-fast evidence rule (schema §3.5): a Claim with no highlight or no evidence
text is rejected — enforced both in `insert_claim` and by NOT NULL / CHECK at
the DB level.

Highlight/Comment status (T33 landed):
- One envelope carries exactly one real highlight, so `highlight.text`,
  `content_hash`, `context_text`, `location_value`, and `order_index` are all
  written from the envelope. Nothing here is a whole-document stand-in any
  more, and `is_temporary_stand_in` is 0.
- `comment` stays empty until a highlight-vs-comment distinction exists (T39):
  the segmenter splits by topic, and does not claim to tell a person's own
  remark apart from the source text.
"""

from __future__ import annotations

import hashlib
import sqlite3
from datetime import datetime, timezone
from pathlib import Path
from typing import Iterable

from gateway.ingestion.ids import deterministic_id, highlight_id_for_highlight
from gateway.ingestion.models import IngestionEnvelope

CONTENT_TABLES = (
    "source",
    "acquisition",
    "highlight",
    "comment",
    "claim",
    "transformation",
    "tag",
)

# T38 (closed): the five controlled vocabularies from METADATA_SCHEMA §3/§7,
# enforced with CHECK constraints below. `location_type` includes `char_range`
# alongside the schema doc's list because that is the value the highlight
# parser actually emits (offsets into the parent document); extend any of
# these only when a query needs the distinction, per the schema's own rule.
# `CREATE TABLE IF NOT EXISTS` means these CHECK constraints only apply to a
# freshly created database — they do not retroactively validate or migrate an
# existing table. That's consistent with T40 (content.db is a disposable,
# nuke-and-rebuild projection from bronze, never a source of truth to patch in
# place); there is no production content.db today (verified 2026-07-29).
SOURCE_TYPES = ("note", "book", "article", "paper", "media", "capture")
LOCATION_TYPES = ("page", "timestamp", "paragraph", "percentage", "unknown", "char_range")
OPERATIONS = ("parse", "ocr_cleanup", "claim_extraction", "summarize")
REVIEW_STATUSES = ("unreviewed", "reviewed", "rejected")
TAG_PROVENANCES = ("source", "imported", "user", "system")

# Origin systems (the capture channel, e.g. "obsidian_note") are not
# themselves a `source_type` — they map to the intellectual-type enum above.
# Fails loud (T38 fix) on anything unmapped rather than reusing the channel
# string as-is, which previously mislabeled every Source row.
ORIGIN_SYSTEM_TO_SOURCE_TYPE = {
    "obsidian_note": "note",  # sources/obsidian.py
    "note": "note",  # sources/markdown_tree.py (non-Obsidian markdown folder)
    "markdown": "note",  # runner.run_document's single-file default
}


def source_type_for_origin(origin_system: str) -> str:
    """Raise ValueError on an unmapped channel (e.g. a new T15/T16/T44/T46 source).

    This propagates out of `project_envelope` -> `ContentConsumer.consume`, and
    the Dispatcher marks the `sqlite` target `failed` for that envelope (R5) —
    KG/vector targets are unaffected and may still succeed. It does not abort
    the whole run; add the new channel's mapping here to fix it.
    """
    try:
        return ORIGIN_SYSTEM_TO_SOURCE_TYPE[origin_system]
    except KeyError:
        raise ValueError(
            f"no source_type mapping for origin_system {origin_system!r}; "
            "add one to ORIGIN_SYSTEM_TO_SOURCE_TYPE"
        ) from None


SCHEMA = f"""
CREATE TABLE IF NOT EXISTS source (
    source_id TEXT PRIMARY KEY,
    source_type TEXT NOT NULL CHECK (source_type IN {SOURCE_TYPES!r}),
    title TEXT,
    authors TEXT,
    source_status TEXT NOT NULL DEFAULT 'resolved',
    canonical_url TEXT,
    publication_date TEXT,
    source_meta TEXT
);

CREATE TABLE IF NOT EXISTS acquisition (
    acquisition_id TEXT PRIMARY KEY,
    source_id TEXT,
    origin_system TEXT NOT NULL,
    origin_record_id TEXT,
    original_path TEXT,
    file_hash TEXT,
    imported_at TEXT NOT NULL,
    pipeline_version TEXT,
    FOREIGN KEY(source_id) REFERENCES source(source_id)
);
CREATE INDEX IF NOT EXISTS idx_acquisition_source ON acquisition(source_id);

CREATE TABLE IF NOT EXISTS highlight (
    highlight_id TEXT PRIMARY KEY,
    acquisition_id TEXT NOT NULL,
    source_id TEXT,
    text TEXT,
    content_hash TEXT,
    context_text TEXT,
    location_type TEXT NOT NULL DEFAULT 'unknown' CHECK (location_type IN {LOCATION_TYPES!r}),
    location_value TEXT,
    order_index INTEGER,
    embedding_model TEXT,
    ingested_at TEXT NOT NULL,
    is_temporary_stand_in INTEGER NOT NULL DEFAULT 0,
    FOREIGN KEY(acquisition_id) REFERENCES acquisition(acquisition_id),
    FOREIGN KEY(source_id) REFERENCES source(source_id)
);
CREATE INDEX IF NOT EXISTS idx_highlight_acquisition ON highlight(acquisition_id);

CREATE TABLE IF NOT EXISTS comment (
    comment_id TEXT PRIMARY KEY,
    highlight_id TEXT NOT NULL,
    text TEXT NOT NULL,
    created_at TEXT NOT NULL,
    FOREIGN KEY(highlight_id) REFERENCES highlight(highlight_id)
);

CREATE TABLE IF NOT EXISTS transformation (
    transformation_id TEXT PRIMARY KEY,
    derived_from TEXT,
    operation TEXT NOT NULL CHECK (operation IN {OPERATIONS!r}),
    tool_or_model TEXT,
    version TEXT,
    prompt_version TEXT,
    created_at TEXT NOT NULL,
    confidence REAL
);

CREATE TABLE IF NOT EXISTS claim (
    claim_id TEXT PRIMARY KEY,
    highlight_id TEXT NOT NULL,
    subject TEXT NOT NULL,
    predicate TEXT NOT NULL,
    object TEXT NOT NULL,
    evidence_text TEXT NOT NULL,
    confidence REAL,
    review_status TEXT NOT NULL DEFAULT 'unreviewed' CHECK (review_status IN {REVIEW_STATUSES!r}),
    created_at TEXT NOT NULL,
    transformation_id TEXT,
    CHECK (length(trim(evidence_text)) > 0),
    FOREIGN KEY(highlight_id) REFERENCES highlight(highlight_id),
    FOREIGN KEY(transformation_id) REFERENCES transformation(transformation_id)
);
CREATE INDEX IF NOT EXISTS idx_claim_highlight ON claim(highlight_id);

CREATE TABLE IF NOT EXISTS tag (
    tag_id TEXT PRIMARY KEY,
    highlight_id TEXT NOT NULL,
    tag TEXT NOT NULL,
    provenance TEXT NOT NULL CHECK (provenance IN {TAG_PROVENANCES!r}),
    FOREIGN KEY(highlight_id) REFERENCES highlight(highlight_id)
);
CREATE INDEX IF NOT EXISTS idx_tag_highlight ON tag(highlight_id);
"""


def _utc_iso() -> str:
    return datetime.now(timezone.utc).isoformat()


def _iso(value: datetime | None) -> str | None:
    return value.isoformat() if value else None


class ContentStore:
    """SQLite-backed store for the seven METADATA_SCHEMA content tables.

    Parameters
    ----------
    path:
        Explicit SQLite file path. Required and configurable — this store never
        defaults to an existing operational database.
    """

    def __init__(self, path: Path) -> None:
        path.parent.mkdir(parents=True, exist_ok=True)
        self.path = path
        self._conn = sqlite3.connect(str(path))
        self._conn.row_factory = sqlite3.Row
        self._conn.execute("PRAGMA foreign_keys=ON")
        self._conn.executescript(SCHEMA)
        self._conn.commit()

    def close(self) -> None:
        self._conn.close()

    # ------------------------------------------------------------------
    # Introspection (used by tests)
    # ------------------------------------------------------------------

    def table_names(self) -> set[str]:
        rows = self._conn.execute(
            "SELECT name FROM sqlite_master WHERE type='table' AND name NOT LIKE 'sqlite_%'"
        ).fetchall()
        return {str(row[0]) for row in rows}

    def rows(self, table: str) -> Iterable[sqlite3.Row]:
        if table not in CONTENT_TABLES:
            raise ValueError(f"Unknown content table: {table}")
        return self._conn.execute(f"SELECT * FROM {table}").fetchall()

    def count(self, table: str) -> int:
        if table not in CONTENT_TABLES:
            raise ValueError(f"Unknown content table: {table}")
        return int(self._conn.execute(f"SELECT COUNT(*) FROM {table}").fetchone()[0])

    # ------------------------------------------------------------------
    # Low-level idempotent writers (each is INSERT OR IGNORE on the PK)
    #
    # Enum columns are validated here, in Python, before the INSERT — not left
    # to the DB's CHECK constraint alone, because `INSERT OR IGNORE` (needed
    # for idempotent redispatch) also silently swallows CHECK violations. The
    # CHECK stays in the schema as a backstop for any other writer; this is
    # the fail-loud path (T38).
    # ------------------------------------------------------------------

    @staticmethod
    def _check_enum(value: str, allowed: tuple[str, ...], field: str) -> None:
        if value not in allowed:
            raise ValueError(f"{field}={value!r} is not one of {allowed}")

    def insert_source(
        self,
        *,
        source_id: str,
        source_type: str,
        title: str | None = None,
        authors: str | None = None,
        source_status: str = "resolved",
        canonical_url: str | None = None,
        publication_date: str | None = None,
        source_meta: str | None = None,
    ) -> None:
        self._check_enum(source_type, SOURCE_TYPES, "source_type")
        self._conn.execute(
            """INSERT OR IGNORE INTO source
               (source_id,source_type,title,authors,source_status,canonical_url,
                publication_date,source_meta)
               VALUES (?,?,?,?,?,?,?,?)""",
            (source_id, source_type, title, authors, source_status, canonical_url,
             publication_date, source_meta),
        )

    def insert_acquisition(
        self,
        *,
        acquisition_id: str,
        source_id: str | None,
        origin_system: str,
        origin_record_id: str | None = None,
        original_path: str | None = None,
        file_hash: str | None = None,
        imported_at: str,
        pipeline_version: str | None = None,
    ) -> None:
        self._conn.execute(
            """INSERT OR IGNORE INTO acquisition
               (acquisition_id,source_id,origin_system,origin_record_id,
                original_path,file_hash,imported_at,pipeline_version)
               VALUES (?,?,?,?,?,?,?,?)""",
            (acquisition_id, source_id, origin_system, origin_record_id,
             original_path, file_hash, imported_at, pipeline_version),
        )

    def insert_highlight(
        self,
        *,
        highlight_id: str,
        acquisition_id: str,
        source_id: str | None,
        text: str | None,
        content_hash: str | None,
        context_text: str | None = None,
        location_type: str = "unknown",
        location_value: str | None = None,
        order_index: int | None = None,
        embedding_model: str | None = None,
        ingested_at: str,
        is_temporary_stand_in: bool = False,
    ) -> None:
        self._check_enum(location_type, LOCATION_TYPES, "location_type")
        self._conn.execute(
            """INSERT OR IGNORE INTO highlight
               (highlight_id,acquisition_id,source_id,text,content_hash,context_text,
                location_type,location_value,order_index,embedding_model,ingested_at,
                is_temporary_stand_in)
               VALUES (?,?,?,?,?,?,?,?,?,?,?,?)""",
            (highlight_id, acquisition_id, source_id, text, content_hash, context_text,
             location_type, location_value, order_index, embedding_model, ingested_at,
             int(is_temporary_stand_in)),
        )

    def insert_comment(
        self, *, comment_id: str, highlight_id: str, text: str, created_at: str
    ) -> None:
        self._conn.execute(
            """INSERT OR IGNORE INTO comment (comment_id,highlight_id,text,created_at)
               VALUES (?,?,?,?)""",
            (comment_id, highlight_id, text, created_at),
        )

    def insert_transformation(
        self,
        *,
        transformation_id: str,
        derived_from: str | None,
        operation: str,
        tool_or_model: str | None = None,
        version: str | None = None,
        prompt_version: str | None = None,
        created_at: str,
        confidence: float | None = None,
    ) -> None:
        self._check_enum(operation, OPERATIONS, "operation")
        self._conn.execute(
            """INSERT OR IGNORE INTO transformation
               (transformation_id,derived_from,operation,tool_or_model,version,
                prompt_version,created_at,confidence)
               VALUES (?,?,?,?,?,?,?,?)""",
            (transformation_id, derived_from, operation, tool_or_model, version,
             prompt_version, created_at, confidence),
        )

    def insert_claim(
        self,
        *,
        claim_id: str,
        highlight_id: str,
        subject: str,
        predicate: str,
        object: str,
        evidence_text: str,
        confidence: float | None = None,
        review_status: str = "unreviewed",
        created_at: str,
        transformation_id: str | None = None,
    ) -> None:
        # Fail-fast evidence rule (schema §3.5) — reject before touching the DB.
        if not highlight_id:
            raise ValueError("claim requires a highlight_id (evidence pointer)")
        if not evidence_text or not evidence_text.strip():
            raise ValueError("claim requires non-empty evidence_text")
        self._check_enum(review_status, REVIEW_STATUSES, "review_status")
        self._conn.execute(
            """INSERT OR IGNORE INTO claim
               (claim_id,highlight_id,subject,predicate,object,evidence_text,
                confidence,review_status,created_at,transformation_id)
               VALUES (?,?,?,?,?,?,?,?,?,?)""",
            (claim_id, highlight_id, subject, predicate, object, evidence_text,
             confidence, review_status, created_at, transformation_id),
        )

    def insert_tag(
        self, *, tag_id: str, highlight_id: str, tag: str, provenance: str
    ) -> None:
        self._check_enum(provenance, TAG_PROVENANCES, "provenance")
        self._conn.execute(
            """INSERT OR IGNORE INTO tag (tag_id,highlight_id,tag,provenance)
               VALUES (?,?,?,?)""",
            (tag_id, highlight_id, tag, provenance),
        )

    # ------------------------------------------------------------------
    # Replacement (supersede) — delete-and-redo, provenance-scoped
    # ------------------------------------------------------------------

    def delete_for_highlight(self, highlight_id: str) -> None:
        """Remove a highlight and everything derived from it (children first).

        Scoped to this highlight only — never a global sweep.
        """
        with self._conn:
            self._conn.execute("DELETE FROM tag WHERE highlight_id=?", (highlight_id,))
            self._conn.execute("DELETE FROM comment WHERE highlight_id=?", (highlight_id,))
            self._conn.execute("DELETE FROM claim WHERE highlight_id=?", (highlight_id,))
            self._conn.execute("DELETE FROM highlight WHERE highlight_id=?", (highlight_id,))

    def delete_for_source(self, source_record_id: str) -> int:
        """Remove every highlight projected from one document, and their children.

        Used when a document is replaced: a document is parsed into N
        highlights, so superseding it retires all N together. Scoped by the
        document's own `acquisition_id`, which each highlight row already
        carries, so the sweep needs no count and cannot reach another document.
        Returns how many highlights were removed.
        """
        acquisition_id = deterministic_id("acquisition", source_record_id)
        rows = self._conn.execute(
            "SELECT highlight_id FROM highlight WHERE acquisition_id=?",
            (acquisition_id,),
        ).fetchall()
        for row in rows:
            self.delete_for_highlight(str(row["highlight_id"]))
        return len(rows)

    # ------------------------------------------------------------------
    # Envelope adapter — one source-unit projection, one transaction
    # ------------------------------------------------------------------

    def project_envelope(self, envelope: IngestionEnvelope) -> str:
        """Project one approved envelope into the seven content tables.

        Runs in a single transaction (atomic: a failure writes nothing). Returns
        the highlight_id used. Idempotent: rerunning the same envelope inserts no
        duplicate rows. If the envelope supersedes another record, the
        predecessor highlight's rows are deleted first (delete-and-redo).

        Mapping:
        - Source: the intellectual thing, keyed off canonical_record_id.
        - Acquisition: this capture channel (bronze ref + raw file hash). One
          per document, shared by all of its highlights.
        - Highlight: this envelope's own highlight — real text, its own content
          hash, its surrounding context, and its character range in the parent
          document as `location_value`.
        - Claim rows come from BOTH approved RelationProposals (real triples) and
          "current" ClaimProposals (subject=concept label, predicate=ASSERTS,
          object=claim text), mirroring the KG consumer.
        - Transformation: one claim_extraction row all claims point at.
        - Tag: envelope field_tags as provenance='system' (machine-inferred).
        - Comment: none (T39 — the segmenter splits by topic, not by author).
        """
        if envelope.supersedes_record_id:
            self.delete_for_source(envelope.supersedes_record_id)

        source_id = deterministic_id("source", envelope.canonical_record_id)
        acquisition_id = deterministic_id("acquisition", envelope.source_record_id)
        highlight_id: str = highlight_id_for_highlight(
            envelope.source_record_id, envelope.highlight_index
        )
        transformation_id = deterministic_id(
            "transformation", envelope.envelope_id, envelope.extraction_version
        )
        now = _utc_iso()

        with self._conn:
            self.insert_source(
                source_id=source_id,
                source_type=source_type_for_origin(envelope.source_type),
                title=str(envelope.metadata.get("title")) if envelope.metadata.get("title") else None,
                source_status="resolved",
                canonical_url=envelope.origin,
            )
            self.insert_acquisition(
                acquisition_id=acquisition_id,
                source_id=source_id,
                origin_system=envelope.source_type,
                origin_record_id=envelope.source_record_id,
                original_path=envelope.raw_content_ref,
                file_hash=envelope.raw_content_hash,
                imported_at=_iso(envelope.captured_at) or now,
                pipeline_version=envelope.extraction_version,
            )
            self.insert_highlight(
                highlight_id=highlight_id,
                acquisition_id=acquisition_id,
                source_id=source_id,
                text=envelope.highlight_text,
                content_hash=hashlib.sha256(
                    envelope.highlight_text.encode("utf-8")
                ).hexdigest(),
                context_text=envelope.highlight_context_text,
                location_type="char_range",
                location_value=(
                    f"{envelope.highlight_start_char}:{envelope.highlight_end_char}"
                ),
                order_index=envelope.highlight_index,
                ingested_at=_iso(envelope.created_at) or now,
                is_temporary_stand_in=False,
            )
            self.insert_transformation(
                transformation_id=transformation_id,
                derived_from=highlight_id,
                operation="claim_extraction",
                tool_or_model=envelope.extraction_version,
                version=envelope.extraction_version,
                created_at=now,
                confidence=envelope.model_confidence,
            )

            # Claims from approved relation triples.
            for relation in envelope.semantic.relations:
                if relation.status != "approved" or not relation.evidence:
                    continue
                self.insert_claim(
                    claim_id=deterministic_id("content-claim-rel", relation.proposal_id),
                    highlight_id=highlight_id,
                    subject=relation.subject,
                    predicate=relation.predicate,
                    object=relation.object,
                    evidence_text=relation.evidence[0].quote,
                    confidence=relation.model_confidence,
                    review_status="reviewed",
                    created_at=now,
                    transformation_id=transformation_id,
                )

            # Claims from free-text claim proposals (one row per concept label).
            for claim in envelope.semantic.claims:
                if claim.status != "current" or not claim.evidence or not claim.concept_labels:
                    continue
                evidence_text = claim.evidence[0].quote
                for label in claim.concept_labels:
                    self.insert_claim(
                        claim_id=deterministic_id(
                            "content-claim", claim.proposal_id, label
                        ),
                        highlight_id=highlight_id,
                        subject=label,
                        predicate="ASSERTS",
                        object=claim.text,
                        evidence_text=evidence_text,
                        confidence=claim.model_confidence,
                        review_status="reviewed",
                        created_at=now,
                        transformation_id=transformation_id,
                    )

            # Machine-inferred field tags (provenance='system' — never 'source'/'user').
            for field_tag in envelope.semantic.field_tags:
                self.insert_tag(
                    tag_id=deterministic_id("tag", highlight_id, field_tag, "system"),
                    highlight_id=highlight_id,
                    tag=field_tag,
                    provenance="system",
                )

        return highlight_id
