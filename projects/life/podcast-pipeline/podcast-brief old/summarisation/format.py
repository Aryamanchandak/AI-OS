"""
format.py — Convert markdown briefs and transcripts to HTML for Reader.
"""

import html
import markdown
from datetime import datetime, timezone
from core.models import Transcript


def brief_to_html(
    markdown_text: str,
    title: str,
    source_url: str,
    show_name: str,
    profile: str,
) -> str:
    """Convert a markdown brief into clean HTML for Readwise Reader."""
    rendered = markdown.markdown(
        markdown_text,
        extensions=["extra", "sane_lists", "smarty"],
    )

    timestamp = datetime.now(timezone.utc).strftime("%Y-%m-%d %H:%M UTC")

    return f"""<!DOCTYPE html>
<html>
<head>
<meta charset="utf-8">
<title>{html.escape(title)}</title>
</head>
<body>
<header>
  <p><strong>Show:</strong> {html.escape(show_name)} &middot;
     <strong>Profile:</strong> {html.escape(profile)} &middot;
     <strong>Generated:</strong> {timestamp}</p>
  <p><a href="{html.escape(source_url)}">Source: {html.escape(source_url)}</a></p>
  <hr>
</header>

<article>
{rendered}
</article>

<footer>
  <hr>
  <p><em>Generated by podcast-brief pipeline.</em></p>
</footer>
</body>
</html>"""


def transcript_to_html(
    transcript: Transcript,
    title: str,
    source_url: str,
    show_name: str = "",
) -> str:
    """Convert a transcript to clean HTML for reading on Reader."""
    timestamp = datetime.now(timezone.utc).strftime("%Y-%m-%d %H:%M UTC")

    # Group consecutive utterances by speaker
    blocks = []
    current_speaker = None
    current_lines = []
    current_start_ts = ""

    for seg in transcript.segments:
        if seg.speaker != current_speaker:
            if current_lines:
                blocks.append((current_speaker, current_start_ts, " ".join(current_lines)))
            current_speaker = seg.speaker
            current_start_ts = seg.timestamp
            current_lines = [seg.text]
        else:
            current_lines.append(seg.text)

    if current_lines:
        blocks.append((current_speaker, current_start_ts, " ".join(current_lines)))

    body_parts = []
    for speaker, ts, text in blocks:
        body_parts.append(
            f'<p><strong>{html.escape(speaker)}</strong> '
            f'<span style="color:#888">[{ts}]</span><br>'
            f'{html.escape(text)}</p>'
        )

    body = "\n".join(body_parts)

    show_part = f"<strong>Show:</strong> {html.escape(show_name)} &middot; " if show_name else ""

    return f"""<!DOCTYPE html>
<html>
<head>
<meta charset="utf-8">
<title>Transcript: {html.escape(title)}</title>
</head>
<body>
<header>
  <h1>Transcript: {html.escape(title)}</h1>
  <p>{show_part}<strong>Generated:</strong> {timestamp}</p>
  <p><a href="{html.escape(source_url)}">Source: {html.escape(source_url)}</a></p>
  <hr>
</header>

<article>
{body}
</article>

<footer>
  <hr>
  <p><em>Transcript generated by podcast-brief pipeline. Speakers identified by AI; verify before quoting.</em></p>
</footer>
</body>
</html>"""
